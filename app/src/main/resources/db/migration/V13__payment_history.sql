-- Refunds and payouts get one row per attempt, so a failed attempt is kept instead of written over.
--
-- A payment row is now the charge alone. Where its money is lives in status: SUCCESS means we hold
-- it, then REFUNDING, REFUND_FAILED (waiting for the retry sweep) and REFUNDED once it is back with the
-- payer. These replace refund_status one for one, and the claim on a refund is still one conditional
-- update of that status, so two refunds triggered together still send the money back once.
--
-- Each attempt at sending it back is a row in refunds, with its amount, outcome and reason. A payment
-- has at most one attempt in flight.
--
-- Each attempt at paying a host is a row in payouts, with its own reference, amount, outcome and
-- reason. A hangout has at most one transfer in flight or done, so a second sweep can never pay the
-- host twice. The payout account keeps only where the money goes.

ALTER TABLE payment_service.payments
    DROP CONSTRAINT payments_status_check;

ALTER TABLE payment_service.payments
    ADD CONSTRAINT payments_status_check CHECK (status IN (
        'PENDING',
        'SUCCESS',
        'FAILED',
        'ABANDONED',
        'REFUNDING',
        'REFUND_FAILED',
        'REFUNDED'
    ));

-- Still at most one payment we hold per person per hangout, now that SUCCESS alone says we hold it
DROP INDEX payment_service.uq_payments_one_live_success_per_user_per_hangout;

CREATE UNIQUE INDEX uq_payments_one_live_success_per_user_per_hangout
    ON payment_service.payments (hangout_id, user_id)
    WHERE status = 'SUCCESS';

ALTER TABLE payment_service.payments
    DROP COLUMN refund_status,
    DROP COLUMN refunded_amount_kobo,
    DROP COLUMN refunded_at;

-- No ON DELETE CASCADE: a payment's refund history must never vanish with it.
CREATE TABLE payment_service.refunds (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    payment_id uuid NOT NULL,
    amount_kobo bigint NOT NULL,
    status character varying(255) NOT NULL,
    failure_reason character varying(255),
    created_at timestamp(6) with time zone NOT NULL,
    settled_at timestamp(6) with time zone,
    CONSTRAINT refunds_pkey PRIMARY KEY (id),
    CONSTRAINT refunds_status_check CHECK (status IN ('REQUESTED', 'PROCESSED', 'FAILED')),
    CONSTRAINT fk_refunds_payment FOREIGN KEY (payment_id)
        REFERENCES payment_service.payments (id)
);

CREATE INDEX idx_refunds_payment_id
    ON payment_service.refunds (payment_id);

CREATE UNIQUE INDEX uq_refunds_one_in_flight_per_payment
    ON payment_service.refunds (payment_id)
    WHERE status = 'REQUESTED';

-- hangout_id has no foreign key, as the hangouts table belongs to another schema, like payments.hangout_id
CREATE TABLE payment_service.payouts (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    hangout_id uuid NOT NULL,
    reference character varying(100) NOT NULL,
    amount_kobo bigint NOT NULL,
    status character varying(255) NOT NULL,
    failure_reason character varying(255),
    created_at timestamp(6) with time zone NOT NULL,
    settled_at timestamp(6) with time zone,
    CONSTRAINT payouts_pkey PRIMARY KEY (id),
    CONSTRAINT payouts_reference_key UNIQUE (reference),
    CONSTRAINT payouts_status_check CHECK (status IN ('IN_FLIGHT', 'SUCCEEDED', 'FAILED'))
);

CREATE INDEX idx_payouts_hangout_id
    ON payment_service.payouts (hangout_id);

CREATE UNIQUE INDEX uq_payouts_one_live_per_hangout
    ON payment_service.payouts (hangout_id)
    WHERE status IN ('IN_FLIGHT', 'SUCCEEDED');

ALTER TABLE payment_service.hangout_payout_accounts
    DROP COLUMN transfer_reference,
    DROP COLUMN paid_out_at,
    DROP COLUMN payout_failure_reason;
