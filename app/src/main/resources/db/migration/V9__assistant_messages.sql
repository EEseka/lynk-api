-- Private chats between one person and the spot assistant inside a hangout.
--
-- Each question and each answer is its own row. Only answers have a status: an answer starts
-- PENDING while it is being written and ends ANSWERED or FAILED. A FAILED answer gives the
-- person their message back.
--
-- Hangout and user ids are plain columns with no foreign keys, because those tables belong to
-- other schemas. The assistant cleans up after itself when it hears an account or a hangout is gone.
-- Discover chats are never stored here; they live in Redis for an hour.
CREATE SCHEMA assistant_service;

CREATE TABLE assistant_service.assistant_messages (
    id uuid NOT NULL,
    hangout_id uuid NOT NULL,
    user_id uuid NOT NULL,
    role character varying(255) NOT NULL,
    status character varying(255),
    content text NOT NULL,
    failure_reason character varying(255),
    input_tokens integer,
    output_tokens integer,
    search_count integer,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT assistant_messages_pkey PRIMARY KEY (id),
    CONSTRAINT assistant_messages_role_check CHECK (role IN ('USER', 'ASSISTANT')),
    CONSTRAINT assistant_messages_status_check CHECK (status IN ('PENDING', 'ANSWERED', 'FAILED')),
    CONSTRAINT assistant_messages_failure_reason_check CHECK (failure_reason IN ('TIMEOUT', 'REFUSED', 'ERROR'))
);

-- The cards under an answer: the assistant's reason, plus the same small snapshot of the place a
-- saved spot keeps (name, cover photo, category, price level, address, coordinates). An old chat then
-- opens without a Google call per card; tapping a card still fetches the place fresh.
--
-- ON DELETE CASCADE: chats and accounts are cleared with bulk DELETEs, which skip JPA's own
-- cascade, so Postgres removes the cards itself.
CREATE TABLE assistant_service.assistant_spots (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    message_id uuid NOT NULL,
    position integer NOT NULL,
    reason character varying(300) NOT NULL,
    google_place_id character varying(255) NOT NULL,
    name character varying(500) NOT NULL,
    cover_photo_url character varying(2048),
    category character varying(255) NOT NULL,
    price_level character varying(255),
    short_address character varying(1000),
    latitude double precision NOT NULL,
    longitude double precision NOT NULL,
    CONSTRAINT assistant_spots_pkey PRIMARY KEY (id),
    CONSTRAINT uk_assistant_spot_position UNIQUE (message_id, position),
    CONSTRAINT assistant_spots_category_check CHECK (category IN ('LOUNGE', 'CAFE', 'CLUB', 'RESTAURANT', 'ACTIVITY', 'OTHER')),
    CONSTRAINT assistant_spots_price_level_check CHECK (price_level IN ('CHEAP', 'MODERATE', 'EXPENSIVE', 'LUXURY')),
    CONSTRAINT fk_assistant_spots_message FOREIGN KEY (message_id)
        REFERENCES assistant_service.assistant_messages (id) ON DELETE CASCADE
);

-- A chat's history, newest first.
CREATE INDEX idx_assistant_messages_hangout_id_user_id_created_at
    ON assistant_service.assistant_messages (hangout_id, user_id, created_at DESC);

-- Deleting an account removes every message that person sent or was sent.
CREATE INDEX idx_assistant_messages_user_id
    ON assistant_service.assistant_messages (user_id);

-- One answer being written per chat. Two sends at once both try to insert a PENDING answer, and
-- the second one fails here, before anything is spent.
CREATE UNIQUE INDEX uk_assistant_messages_one_pending_per_chat
    ON assistant_service.assistant_messages (hangout_id, user_id)
    WHERE status = 'PENDING';

-- The sweep only ever looks for old PENDING answers.
CREATE INDEX idx_assistant_messages_pending_created_at
    ON assistant_service.assistant_messages (created_at)
    WHERE status = 'PENDING';
