-- Which reminders a hangout's host has been sent, one row per kind, in place of the two counters on
-- hangouts (completion_reminders_sent, spot_reminders_sent).
--
-- The counters lived on the hangout row, so every sweep that marked one had to bump the hangout's
-- version, and a host saving an edit at that moment was refused for bookkeeping. Rows here never touch
-- the hangout. The unique key means a kind is sent once per hangout even if two sweeps ever run at the
-- same time: the second one fails before it sends anything. A new kind of reminder is a new enum value,
-- not a new column.
--
-- Moving a hangout's date deletes its spot reminders, so the new date gets its own. The rows go with
-- the hangout when it is deleted.
CREATE TABLE hangout_service.hangout_reminders (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    hangout_id uuid NOT NULL,
    kind character varying(255) NOT NULL,
    sent_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT hangout_reminders_pkey PRIMARY KEY (id),
    CONSTRAINT hangout_reminders_kind_check CHECK (kind IN (
        'SPOT_BEFORE_START',
        'SPOT_AFTER_START',
        'COMPLETION_DAY_1',
        'COMPLETION_DAY_3',
        'COMPLETION_DAY_7',
        'SOLO_BEFORE_START'
    )),
    CONSTRAINT uk_hangout_reminders_hangout_kind UNIQUE (hangout_id, kind),
    CONSTRAINT fk_hangout_reminders_hangout FOREIGN KEY (hangout_id)
        REFERENCES hangout_service.hangouts (id) ON DELETE CASCADE
);

ALTER TABLE hangout_service.hangouts
    DROP COLUMN completion_reminders_sent,
    DROP COLUMN spot_reminders_sent;
